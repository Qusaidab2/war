const languageButtons = document.querySelectorAll(".lang-btn");
const translatableElements = document.querySelectorAll("[data-i18n]");

function setLanguage(language) {
  const dictionary = translations[language];

  if (!dictionary) return;

  document.documentElement.lang = language;

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      // The translation strings are defined locally in this file.
      // Their HTML is intentional, for line breaks and highlighted words.
      element.innerHTML = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const selected = button.dataset.lang === language;

    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });

  const titles = {
    en: "War Has No Winners | Humanity First",
    uk: "У війни немає переможців | Людяність понад усе",
    ru: "У войны нет победителей | Человечность прежде всего"
  };

  document.title = titles[language];
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

// Start in English.
setLanguage("en");
